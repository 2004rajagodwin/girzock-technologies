function q($v) { return $v === NULL ? 'NULL' : "'".str_replace(array('\\', "'"), array('\\\\', "''"), (string) $v)."'"; }
function ins($table, array $rows) {
	if ( ! $rows) { return ''; }
	$cols = array_keys($rows[0]);
	$sql = 'INSERT INTO `'.$table.'` (`'.implode('`,`', $cols)."`) VALUES\n";
	$lines = array();
	foreach ($rows as $r) { $lines[] = '('.implode(',', array_map('q', array_values($r))).')'; }
	return $sql.implode(",\n", $lines).";\n\n";
}
